"""End-to-end with the real comparators, on incidents that share a cause.

``test_pipeline.py`` drives the same use cases through a scalar test double. That
is the right test for the orchestration and the governance, and it is the wrong
one for everything below them: with a scalar signature per incident, no profile
is built, no background is consulted, no conjugate model is evaluated, and the
fusion model never sees four streams generated by one operator running one
operation. Every defect in that seam is invisible to it.

These tests put the analysis layer on the path. What they assert is **structure**,
not performance — the same standard ``test_synthetic_incidents.py`` sets, and for
a stronger reason here: the corpus is simulated, so a performance figure taken off
it would be a property of the generative parameters. §11 of the results document
was withdrawn for exactly that, and nothing in this file may be quoted as a
measurement.

The one near-numeric assertion, on the ordering of median fused values, is a
wiring check. It fails if payloads are handed to the wrong stream or a calibrator
comes out sign-inverted, which are the defects this seam actually produces. It is
not a claim that the system discriminates at any rate.
"""

